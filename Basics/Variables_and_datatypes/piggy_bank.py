# A program to calculate the total amount of any piggy bank given in the coins rs 10, rs 5 rs 2 and rs 1
num10=int(input("Enter the number of the coin of rs 10 :- "))
num5=int(input("Enter the number of the coin of rs 5 :- "))
num2=int(input("Enter the number of the coin of rs 2 :- "))
num1=int(input("Enter the number of the coin of rs 1 :- "))
total=(num10*10)+(num5*5)+(num1*1)+(num2*2)
print("The total amount that stay in the piggy bank is :- ",total)
