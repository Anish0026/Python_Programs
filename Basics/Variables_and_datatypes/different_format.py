# take a num as an input and prints its hex , oct and square root format
num=int(input("Enter any number :- "))
print(f"The hex format of the number {num} is :-",hex(num))
print(f"The oct format of the number {num} is :-",oct(num))
print(f"The square root format of the number {num} is :-",num**0.5)
